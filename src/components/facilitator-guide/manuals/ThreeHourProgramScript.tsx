/**
 * interACT 3-Hour Program — facilitator script (combined workshop)
 */

export function ThreeHourProgramScript() {
  return (
    <div className="space-y-10 text-text-muted text-sm leading-relaxed">
      <p className="text-xs font-semibold uppercase tracking-wide text-amber-900">
        interACT 3-Hour Program · Full ACT arc in one session · Use with quiet room and
        breaks as written
      </p>

      <ScriptBlock
        time="0:00 – 0:05"
        title="Welcome & set tone"
        lines={[
          "Say:",
          "“Welcome everyone. Today is not about learning something new… it’s about experiencing something that’s already within you.”",
          "Pause (3–5 seconds)",
          "“Before we begin, just notice how you’re arriving right now—your thoughts, your state… no need to change anything.”",
        ]}
      />

      <ScriptBlock
        time="0:05 – 0:10"
        title="Opening question"
        lines={[
          "Say:",
          "“Quick question—how many of you feel that your mind is constantly busy?”",
          "(Show of hands)",
          "“Today, we’re going to explore something very simple… If my mind is busy… who is the one noticing that?”",
          "Pause",
        ]}
      />

      <section>
        <h2 className="text-lg font-semibold text-teal-800 mb-4 border-b border-teal-100 pb-2">
          AWARENESS · 0:10 – 1:00
        </h2>

        <ScriptBlock
          time="0:10 – 0:20"
          title="Activity: Who am I?"
          lines={[
            "Say:",
            "“Take a moment and write down 5 answers to the question: Who am I?”",
            "(Wait 3–4 minutes)",
            "Then say:",
            "“Now look at your answers… Are these who you are… or roles you play?”",
            "Pause",
          ]}
        />

        <ScriptBlock
          time="0:20 – 0:30"
          title="Shift to observer"
          lines={[
            "Say slowly:",
            "“If I say… ‘my thoughts’… Then who is the ‘me’?”",
            "Pause (important)",
            "“If I can observe my thoughts… It means I am not my thoughts.”",
            "Let that sit. Don’t rush.",
          ]}
        />

        <ScriptBlock
          time="0:30 – 0:45"
          title="Guided awareness experience"
          lines={[
            "Say (soft tone):",
            "“Just sit comfortably… Gently close your eyes if you’re comfortable…”",
            "“Notice your thoughts… Not trying to stop them… just observing…”",
            "(Pause 20 sec)",
            "“Now shift your attention… To the one who is observing…”",
            "(Pause)",
            "“There is a quiet presence… behind the thoughts…”",
            "(Pause 30 sec)",
          ]}
        />

        <ScriptBlock
          time="0:45 – 1:00"
          title="Introduce inner qualities"
          lines={[
            "Say:",
            "“Within this awareness… there are natural qualities…”",
            "“Peace… Calm… A sense of being okay…”",
            "(Pause between each)",
            "“Not something you create… Something you reconnect with…”",
          ]}
        />
      </section>

      <section>
        <h2 className="text-lg font-semibold text-rose-800 mb-4 border-b border-rose-100 pb-2">
          CONTEMPLATION · 1:00 – 1:50
        </h2>

        <ScriptBlock
          time="1:00 – 1:10"
          title="Transition"
          lines={[
            "Say:",
            "“Now that we’ve touched this space… The question is—how do we strengthen it?”",
          ]}
        />

        <ScriptBlock
          time="1:10 – 1:30"
          title="Focus on one quality (peace)"
          lines={[
            "Say:",
            "“Let’s take one quality—peace.”",
            "“Think of a moment when you felt peaceful…”",
            "(Pause 20 sec)",
            "“Now instead of thinking about it… Try to feel it again…”",
            "(Pause 1 min)",
            "“Stay with that feeling…”",
          ]}
        />

        <ScriptBlock
          time="1:30 – 1:40"
          title="Deepen reflection"
          lines={[
            "Ask:",
            "“What usually disturbs this peace?”",
            "(Pause, allow responses or silent reflection)",
            "“Is it the situation… Or how I respond to it?”",
          ]}
        />

        <ScriptBlock
          time="1:40 – 1:50"
          title="Silent practice"
          lines={[
            "Say:",
            "“Let’s spend a few moments in silence…”",
            "“Just being with this feeling…”",
            "(3–4 minutes silence — do NOT interrupt)",
            "Then gently:",
            "“Slowly bring your awareness back…”",
          ]}
        />
      </section>

      <ScriptBlock
        time="1:50 – 2:00"
        title="Break"
        lines={[
          "Keep it short. Don’t lose the energy.",
        ]}
      />

      <section>
        <h2 className="text-lg font-semibold text-indigo-800 mb-4 border-b border-indigo-100 pb-2">
          TRANSFORMATIVE SILENCE · 2:00 – 2:40
        </h2>

        <ScriptBlock
          time="2:00 – 2:10"
          title="Redefining silence"
          lines={[
            "Say:",
            "“When we say silence… we don’t mean absence of sound…”",
            "“We mean a state where the mind becomes clear… And you feel internally strong.”",
          ]}
        />

        <ScriptBlock
          time="2:10 – 2:30"
          title="Guided transformative silence"
          lines={[
            "Say slowly:",
            "“Close your eyes…”",
            "“Notice your thoughts…”",
            "(Pause)",
            "“Now… gently let them settle…”",
            "(Pause)",
            "“Shift your attention inward…”",
            "(Pause)",
            "“There is a deeper source of calm… A space of clarity…”",
            "(Pause longer — 1–2 min total silence)",
            "“Stay there…”",
            "⚠️ This is the most important silence—don’t rush",
          ]}
        />

        <ScriptBlock
          time="2:30 – 2:40"
          title="Reflection"
          lines={[
            "Ask softly:",
            "“What did you notice?”",
            "Let 2–3 people share.",
          ]}
        />
      </section>

      <section>
        <h2 className="text-lg font-semibold text-slate-800 mb-4 border-b border-slate-200 pb-2">
          INTEGRATION · 2:40 – 3:00
        </h2>

        <ScriptBlock
          time="2:40 – 2:50"
          title="Real-life application"
          lines={[
            "Say:",
            "“Think of a situation where you usually feel stressed…”",
            "(Pause)",
            "“Now imagine responding from this state… What would be different?”",
          ]}
        />

        <ScriptBlock
          time="2:50 – 2:55"
          title="Daily practice"
          lines={[
            "Say:",
            "“You don’t need hours to practice this.”",
            "“Just 5 minutes a day:",
            "1 min: pause and observe",
            "2 min: feel a quality",
            "2 min: sit in silence”",
          ]}
        />

        <ScriptBlock
          time="2:55 – 3:00"
          title="Closing"
          lines={[
            "Say slowly:",
            "“Everything you experienced today… Was already within you.”",
            "“Our work is simply to return to it.”",
            "Pause.",
            "“Thank you.”",
          ]}
        />
      </section>

      <section className="rounded-2xl border-2 border-amber-200 bg-amber-50/60 p-6">
        <h2 className="text-lg font-semibold text-amber-900 mb-3">
          Facilitator reminders (keep visible)
        </h2>
        <ul className="list-disc pl-5 space-y-2 text-amber-950/90">
          <li>Slow down more than you think you should.</li>
          <li>Silence is not awkward—it’s powerful.</li>
          <li>Don’t over-explain the experience.</li>
          <li>Your state matters more than your words.</li>
        </ul>
      </section>
    </div>
  );
}

function ScriptBlock({
  time,
  title,
  lines,
}: {
  time: string;
  title: string;
  lines: string[];
}) {
  return (
    <div className="mb-6 rounded-xl border border-gray-100 bg-white p-5 shadow-sm">
      <div className="flex flex-wrap items-baseline gap-2 mb-3">
        <span className="text-xs font-semibold uppercase tracking-wide text-teal-700">
          {time}
        </span>
        <span className="font-semibold text-text-main">{title}</span>
      </div>
      <div className="space-y-2 whitespace-pre-line">
        {lines.map((line, idx) => (
          <p key={idx}>{line}</p>
        ))}
      </div>
    </div>
  );
}
